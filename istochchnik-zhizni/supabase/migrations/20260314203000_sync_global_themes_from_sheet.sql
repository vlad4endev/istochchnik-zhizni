    bible_verse = s.bible_verse,
    prayer_points = s.prayer_points
  from source_themes s
  where lower(trim(g.title)) = lower(trim(s.title))
  returning g.id
)
insert into public.global_themes (title, bible_verse, prayer_points)
select s.title, s.bible_verse, s.prayer_points
from source_themes s
where not exists (
  select 1
  from public.global_themes g
  where lower(trim(g.title)) = lower(trim(s.title))
);
